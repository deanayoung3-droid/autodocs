export type SpriteName = keyof typeof SPRITES;

/** One sprite, drawn with square cells. Decorative, so hidden from assistive tech. */
export function Sprite({ name, size = 32, className = "" }: { name: SpriteName; size?: number; className?: string }) {
  const art: Art = SPRITES[name];
  const fill: Record<string, string> = { k: K, w: W, ...art.colors };
  return (
    <svg width={size} height={size} viewBox="0 0 16 16" shapeRendering="crispEdges" aria-hidden className={`shrink-0 ${className}`}>
      {art.rows.flatMap((row, y) =>
        [...row].map((c, x) => (fill[c] ? <rect key={`${x}-${y}`} x={x + 2} y={y + 2} width={1} height={1} fill={fill[c]} /> : null)),
      )}
    </svg>
  );
}
